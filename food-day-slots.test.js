const assert=require('node:assert/strict');
const DS=require('./food-day-slots.js');
const SL=require('./food-slots.js');
global.ChapiFoodTotalsBridge=require('./food-totals-bridge.js');
const C=require('./core.js');
const settings=SL.change(SL.defaults(),{type:'add',id:'snack-abcdef',name:'夜食'});
const fresh=DS.snapshot({},false,settings);
assert.equal(fresh.length,5);
assert.equal(fresh[4].slotName,'夜食');
assert.equal(DS.snapshot({},true,settings).length,4);
const day=DS.withMeal({meals:{breakfast:{kcal:400,p:20,f:10,c:60}}},false,settings,'snack-abcdef',{format:'chapi-food-record-2-draft',totalMode:'manual',manualTotal:{kcal:100,p:5,f:3,c:12},entries:[]});
assert.equal(C.foodTotals(day).total.kcal,500);
assert.equal(C.foodTotals(day).total.p,25);
assert.equal(C.foodTotals(day).count.kcal,2);
const old=DS.withMeal(day,true,SL.defaults(),'breakfast',{format:'chapi-food-record-2-draft',totalMode:'legacy',manualTotal:{kcal:400,p:20,f:10,c:60},entries:[]});
assert.equal(old.foodV2.slots.length,5);
assert.equal(C.foodTotals(old).total.kcal,500);
const erased=DS.withMeal(day,true,settings,'snack-abcdef',null);
assert.equal(C.foodTotals(erased).total.kcal,400);
assert.equal(day.foodV2.slots[4].meal.manualTotal.kcal,100);
assert.throws(()=>DS.withMeal({},true,settings,'snack-abcdef',null),/ありません/);
console.log('day slot snapshot and extra totals checks passed');
