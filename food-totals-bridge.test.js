const assert=require('node:assert/strict');
global.ChapiFoodTotalsBridge=require('./food-totals-bridge.js');
const core=require('./core.js');
const n=(kcal,p,f,c)=>({kcal,p,f,c});
const slot=(slotId,meal)=>({slotId,slotName:slotId,slotOrder:0,meal});
const day=slots=>({foodV2:{format:'chapi-food-day-2',slots}});
const b=slot('breakfast',{entries:[{kind:'dish',calculationMode:'estimate',estimate:n(400,20,10,50),ingredients:[n(100,2,1,5)]}]});
const l=slot('lunch',{totalMode:'manual',manualTotal:n(800,30,20,90),entries:[n(50,1,2,3)]});
const d=slot('dinner',{skipped:true});
const x=core.foodTotals(day([b,l,d]));
assert.deepEqual(x.total,n(1200,50,30,140));assert.equal(x.complete,true);assert.equal(x.count.kcal,3);
const partial=core.foodTotals(day([slot('breakfast',{entries:[{kcal:200,p:null,f:5,c:20}]}),l,d]));
assert.equal(partial.total.p,30);assert.equal(partial.count.p,2);assert.equal(partial.total.kcal,1000);
assert.equal(core.foodTotals(day([b,l])).complete,false);
assert.equal(core.foodTotals(day([b,l,d,slot('snack-1',{entries:[n(100,5,2,15)]})])).total.kcal,1300);
assert.equal(core.foodTotals(day([b,l,d,slot('snack-1',null)])).total.kcal,1200);
assert.equal(core.foodTotals(day([b,l,d,slot('snack-1',{totalMode:'legacy',manualTotal:{kcal:80,p:null,f:null,c:null}})])).total.kcal,1280);
assert.deepEqual(core.foodTotals({meals:{breakfast:n(300,20,5,40)}}).total,n(300,20,5,40));
assert.deepEqual(core.foodTotals({meals:{breakfast:n(300,20,5,40)},foodV2:{format:'chapi-food-day-2-draft',slots:[b,l,d]}}).total,n(300,20,5,40));
assert.throws(()=>core.foodTotals(day([b,b])),/ID/);
console.log('food totals bridge: 9 checks passed');
